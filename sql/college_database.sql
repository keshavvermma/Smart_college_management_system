-- Attendance per student per subject
CREATE VIEW vw_attendance_summary AS
SELECT  st.student_id, st.roll_no, st.name AS student_name, st.gender,
        d.department_id, d.dept_name, st.semester, st.admission_year,
        sb.subject_id, sb.subject_code, sb.subject_name, sb.faculty_id,
        COUNT(a.attendance_id)                                AS total_classes,
        SUM(CASE WHEN a.status = 'Present' THEN 1 ELSE 0 END) AS present_classes,
        ROUND(100 * SUM(CASE WHEN a.status = 'Present' THEN 1 ELSE 0 END)
              / COUNT(a.attendance_id), 2)                    AS attendance_percentage,
        CASE WHEN 100 * SUM(CASE WHEN a.status = 'Present' THEN 1 ELSE 0 END)
                  / COUNT(a.attendance_id) < 75 THEN 'Below 75%' ELSE 'OK' END AS attendance_status
FROM attendance a
JOIN students    st ON st.student_id    = a.student_id
JOIN subjects    sb ON sb.subject_id    = a.subject_id
JOIN departments d  ON d.department_id  = st.department_id
GROUP BY st.student_id, st.roll_no, st.name, st.gender, d.department_id, d.dept_name,
         st.semester, st.admission_year, sb.subject_id, sb.subject_code, sb.subject_name, sb.faculty_id;

-- One row per attendance record (monthly trend in Power BI)
CREATE VIEW vw_attendance_detail AS
SELECT  a.attendance_id, a.date AS attendance_date,
        DATE_FORMAT(a.date, '%Y-%m')    AS month_key,
        DATE_FORMAT(a.date, '%b %Y')    AS month_name,
        a.status,
        CASE WHEN a.status = 'Present' THEN 1 ELSE 0 END AS is_present,
        st.student_id, st.roll_no, st.name AS student_name, st.gender,
        d.dept_name, st.semester, sb.subject_code, sb.subject_name
FROM attendance a
JOIN students    st ON st.student_id   = a.student_id
JOIN subjects    sb ON sb.subject_id   = a.subject_id
JOIN departments d  ON d.department_id = st.department_id;

-- One row per mark entry with percentage, grade and result
CREATE VIEW vw_marks_detail AS
SELECT  m.mark_id, st.student_id, st.roll_no, st.name AS student_name, st.gender,
        d.department_id, d.dept_name, st.semester, st.admission_year,
        sb.subject_id, sb.subject_code, sb.subject_name, sb.faculty_id,
        m.exam_type, m.marks, m.max_marks,
        ROUND(100 * m.marks / m.max_marks, 2) AS percentage,
        CASE WHEN 100 * m.marks / m.max_marks >= 90 THEN 'A+'
             WHEN 100 * m.marks / m.max_marks >= 80 THEN 'A'
             WHEN 100 * m.marks / m.max_marks >= 70 THEN 'B+'
             WHEN 100 * m.marks / m.max_marks >= 60 THEN 'B'
             WHEN 100 * m.marks / m.max_marks >= 50 THEN 'C'
             WHEN 100 * m.marks / m.max_marks >= 40 THEN 'D'
             ELSE 'F' END AS grade,
        CASE WHEN 100 * m.marks / m.max_marks >= 40 THEN 'Pass' ELSE 'Fail' END AS result
FROM marks m
JOIN students    st ON st.student_id   = m.student_id
JOIN subjects    sb ON sb.subject_id   = m.subject_id
JOIN departments d  ON d.department_id = st.department_id;

-- Overall result per student per subject (sum of all exams)
CREATE VIEW vw_student_results AS
SELECT  st.student_id, st.roll_no, st.name AS student_name, st.gender,
        d.department_id, d.dept_name, st.semester, st.admission_year,
        sb.subject_id, sb.subject_code, sb.subject_name, sb.faculty_id,
        SUM(m.marks)     AS total_marks,
        SUM(m.max_marks) AS total_max_marks,
        ROUND(100 * SUM(m.marks) / SUM(m.max_marks), 2) AS percentage,
        CASE WHEN 100 * SUM(m.marks) / SUM(m.max_marks) >= 90 THEN 'A+'
             WHEN 100 * SUM(m.marks) / SUM(m.max_marks) >= 80 THEN 'A'
             WHEN 100 * SUM(m.marks) / SUM(m.max_marks) >= 70 THEN 'B+'
             WHEN 100 * SUM(m.marks) / SUM(m.max_marks) >= 60 THEN 'B'
             WHEN 100 * SUM(m.marks) / SUM(m.max_marks) >= 50 THEN 'C'
             WHEN 100 * SUM(m.marks) / SUM(m.max_marks) >= 40 THEN 'D'
             ELSE 'F' END AS grade,
        CASE WHEN 100 * SUM(m.marks) / SUM(m.max_marks) >= 40 THEN 'Pass' ELSE 'Fail' END AS result
FROM marks m
JOIN students    st ON st.student_id   = m.student_id
JOIN subjects    sb ON sb.subject_id   = m.subject_id
JOIN departments d  ON d.department_id = st.department_id
GROUP BY st.student_id, st.roll_no, st.name, st.gender, d.department_id, d.dept_name,
         st.semester, st.admission_year, sb.subject_id, sb.subject_code, sb.subject_name, sb.faculty_id;

-- One row per student with overall attendance and average marks
CREATE VIEW vw_student_overview AS
SELECT  st.student_id, st.roll_no, st.name AS student_name, st.gender,
        d.dept_name, st.semester, st.admission_year,
        CONCAT(st.admission_year, '-', st.admission_year + 1) AS academic_year,
        (SELECT ROUND(100 * SUM(CASE WHEN a.status = 'Present' THEN 1 ELSE 0 END) / COUNT(*), 2)
           FROM attendance a WHERE a.student_id = st.student_id) AS overall_attendance,
        (SELECT ROUND(100 * SUM(m.marks) / SUM(m.max_marks), 2)
           FROM marks m WHERE m.student_id = st.student_id)      AS overall_marks_percentage
FROM students st
JOIN departments d ON d.department_id = st.department_id;

