DROP DATABASE IF EXISTS smart_college;
CREATE DATABASE smart_college CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE smart_college;

-- ---------------------------------------------------------------------
-- 1. departments
-- ---------------------------------------------------------------------
CREATE TABLE departments (
    department_id INT AUTO_INCREMENT PRIMARY KEY,
    dept_name     VARCHAR(100) NOT NULL,
    dept_code     VARCHAR(10)  NOT NULL,
    UNIQUE KEY uq_dept_name (dept_name),
    UNIQUE KEY uq_dept_code (dept_code)
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- 2. faculty
-- ---------------------------------------------------------------------
CREATE TABLE faculty (
    faculty_id    INT AUTO_INCREMENT PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    email         VARCHAR(120) NOT NULL,
    phone         VARCHAR(15)  NOT NULL,
    department_id INT          NOT NULL,
    designation   VARCHAR(60)  NOT NULL,
    joining_date  DATE         NOT NULL,
    UNIQUE KEY uq_faculty_email (email),
    KEY idx_faculty_dept (department_id),
    CONSTRAINT fk_faculty_dept FOREIGN KEY (department_id)
        REFERENCES departments (department_id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- 3. students
-- ---------------------------------------------------------------------
CREATE TABLE students (
    student_id     INT AUTO_INCREMENT PRIMARY KEY,
    roll_no        VARCHAR(20)  NOT NULL,
    name           VARCHAR(100) NOT NULL,
    gender         ENUM('Male','Female','Other') NOT NULL,
    date_of_birth  DATE         NOT NULL,
    department_id  INT          NOT NULL,
    semester       TINYINT      NOT NULL,
    email          VARCHAR(120) NOT NULL,
    phone          VARCHAR(15)  NOT NULL,
    address        VARCHAR(255) NULL,
    admission_year SMALLINT     NOT NULL,
    UNIQUE KEY uq_student_roll (roll_no),
    UNIQUE KEY uq_student_email (email),
    KEY idx_student_dept_sem (department_id, semester),
    CONSTRAINT chk_student_sem CHECK (semester BETWEEN 1 AND 8),
    CONSTRAINT fk_student_dept FOREIGN KEY (department_id)
        REFERENCES departments (department_id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- 4. subjects  (faculty_id = the teacher assigned to the subject)
-- ---------------------------------------------------------------------
CREATE TABLE subjects (
    subject_id    INT AUTO_INCREMENT PRIMARY KEY,
    subject_code  VARCHAR(12)  NOT NULL,
    subject_name  VARCHAR(100) NOT NULL,
    department_id INT          NOT NULL,
    semester      TINYINT      NOT NULL,
    credits       TINYINT      NOT NULL,
    faculty_id    INT          NULL,
    UNIQUE KEY uq_subject_code (subject_code),
    KEY idx_subject_dept_sem (department_id, semester),
    KEY idx_subject_faculty (faculty_id),
    CONSTRAINT chk_subject_sem CHECK (semester BETWEEN 1 AND 8),
    CONSTRAINT chk_subject_credits CHECK (credits BETWEEN 1 AND 6),
    CONSTRAINT fk_subject_dept FOREIGN KEY (department_id)
        REFERENCES departments (department_id) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_subject_faculty FOREIGN KEY (faculty_id)
        REFERENCES faculty (faculty_id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- 5. users  (login accounts; ref_id points to students/faculty by role)
-- ---------------------------------------------------------------------
CREATE TABLE users (
    user_id       INT AUTO_INCREMENT PRIMARY KEY,
    username      VARCHAR(60)  NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role          ENUM('admin','faculty','student') NOT NULL,
    ref_id        INT NULL COMMENT 'student_id or faculty_id (NULL for admin)',
    created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uq_username (username),
    KEY idx_users_role_ref (role, ref_id)
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- 6. attendance  (one row per student, subject and date)
-- ---------------------------------------------------------------------
CREATE TABLE attendance (
    attendance_id INT AUTO_INCREMENT PRIMARY KEY,
    student_id    INT  NOT NULL,
    subject_id    INT  NOT NULL,
    faculty_id    INT  NULL,
    date          DATE NOT NULL,
    status        ENUM('Present','Absent') NOT NULL,
    UNIQUE KEY uq_attendance (student_id, subject_id, date),
    KEY idx_att_subject_date (subject_id, date),
    CONSTRAINT fk_att_student FOREIGN KEY (student_id)
        REFERENCES students (student_id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_att_subject FOREIGN KEY (subject_id)
        REFERENCES subjects (subject_id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_att_faculty FOREIGN KEY (faculty_id)
        REFERENCES faculty (faculty_id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- 7. marks  (one row per student, subject and exam type)
-- ---------------------------------------------------------------------
CREATE TABLE marks (
    mark_id    INT AUTO_INCREMENT PRIMARY KEY,
    student_id INT NOT NULL,
    subject_id INT NOT NULL,
    exam_type  ENUM('Internal','Mid Term','Practical','End Semester') NOT NULL,
    marks      DECIMAL(6,2) NOT NULL,
    max_marks  DECIMAL(6,2) NOT NULL,
    UNIQUE KEY uq_marks (student_id, subject_id, exam_type),
    KEY idx_marks_subject (subject_id),
    CONSTRAINT chk_marks_range CHECK (marks >= 0 AND max_marks > 0 AND marks <= max_marks),
    CONSTRAINT fk_marks_student FOREIGN KEY (student_id)
        REFERENCES students (student_id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_marks_subject FOREIGN KEY (subject_id)
        REFERENCES subjects (subject_id) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- 8. notices
-- ---------------------------------------------------------------------
CREATE TABLE notices (
    notice_id    INT AUTO_INCREMENT PRIMARY KEY,
    title        VARCHAR(150) NOT NULL,
    description  TEXT         NOT NULL,
    created_by   INT          NULL,
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    priority     ENUM('Normal','Important','Urgent') NOT NULL DEFAULT 'Normal',
    is_published TINYINT(1)   NOT NULL DEFAULT 1,
    KEY idx_notice_created (created_at),
    CONSTRAINT fk_notice_user FOREIGN KEY (created_by)
        REFERENCES users (user_id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- 9. timetable
-- ---------------------------------------------------------------------
CREATE TABLE timetable (
    timetable_id  INT AUTO_INCREMENT PRIMARY KEY,
    department_id INT NOT NULL,
    semester      TINYINT NOT NULL,
    subject_id    INT NOT NULL,
    day_of_week   ENUM('Monday','Tuesday','Wednesday','Thursday','Friday','Saturday') NOT NULL,
    start_time    TIME NOT NULL,
    end_time      TIME NOT NULL,
    room          VARCHAR(30) NULL,
    KEY idx_tt_dept_sem (department_id, semester),
    KEY idx_tt_subject (subject_id),
    CONSTRAINT chk_tt_time CHECK (end_time > start_time),
    CONSTRAINT fk_tt_dept FOREIGN KEY (department_id)
        REFERENCES departments (department_id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_tt_subject FOREIGN KEY (subject_id)
        REFERENCES subjects (subject_id) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB;


